"""Translate the pinned RMX2072 60 Hz DSI command packets without changing bytes."""
import argparse
import hashlib
import json
from pathlib import Path
import re

SOURCE_SHA = '219f47d58006b129d9f46628389c161283debc5e04892e88ad6ff02a12074372'


def packets(data):
    result = []
    while data:
        if len(data) < 7:
            raise ValueError('Truncated Qualcomm command header')
        dtype, last, channel, ack, delay, hi, lo = data[:7]
        length = hi * 256 + lo
        if (dtype not in (0x05, 0x15, 0x39) or last != 1 or channel != 0
                or ack != 0 or not 0 < length <= 128 or len(data) < 7 + length):
            raise ValueError('Unexpected DSI packet in pinned 60 Hz sequence')
        result.append((dtype, delay, data[7:7 + length]))
        data = data[7 + length:]
    return result


def generate(source):
    # Git checkouts on Windows may have CRLF; the lock names the Git blob.
    data = source.replace(b'\r\n', b'\n')
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA:
        raise ValueError('Panel source does not match the pinned official Git blob')
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', data.decode(), flags=re.S)
    timing = text.split('timing@0', 1)[1].split('timing@1', 1)[0]
    out = ['/* SPDX-License-Identifier: GPL-2.0-only */',
           '/* Generated by scripts/build/import_rm19795_panel.py; do not edit.',
           ' * Official realme Android Q commit 24a15224fbae8ab0e8ba29a9046c06ee7a9f53a4.',
           ' * RM19795 Samsung panel, 1080x2400, 60 Hz. Packet types and delays preserved.',
           ' */', '']
    counts = {}
    for name, prop in [('on', 'on-command'), ('enable', 'post-on-backlight'), ('off', 'off-command')]:
        value = re.search(r'qcom,mdss-dsi-' + prop + r'\s*=\s*\[([^]]+)\]', timing)
        if value is None:
            raise ValueError('Missing command list: ' + prop)
        raw = bytes.fromhex(value[1])
        seq = packets(raw)
        counts[name] = dict(count=len(seq), sha256=hashlib.sha256(raw).hexdigest())
        out.append(f'static const struct rm19795_cmd rm19795_cmd_{name}[] = {{')
        for dtype, delay, payload in seq:
            out.append(f'\t{{ 0x{dtype:02x}, {delay}, {len(payload)}, {{ ' +
                       ', '.join(f'0x{b:02x}' for b in payload) + ' } },')
        out.extend(['};', ''])
    return '\n'.join(out), counts


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    output, counts = generate(a.source.read_bytes())
    if a.check:
        if a.output.read_text() != output:
            raise ValueError('Generated command table differs from the official source')
    else:
        a.output.parent.mkdir(parents=True, exist_ok=True)
        a.output.write_text(output, newline='\n')
    print(json.dumps(dict(source_sha256=SOURCE_SHA, commands=counts)))


if __name__ == '__main__':
    main()
